/**
 * 16x16 pixel icon maps.
 *   '#' = currentColor, '+' = currentColor at half opacity (shade), '.' = empty.
 * Plain data + tiny helpers only (no JSX) so a node script can import it.
 */
export type PixelRows = readonly string[];

const SIZE = 16;

/** Dim every pixel and draw a bold diagonal slash with a clear gap around it. */
function withSlash(rows: PixelRows): string[] {
  const g = rows.map((r) => r.split(""));
  for (const row of g) {
    for (let x = 0; x < SIZE; x++) {
      if (row[x] === "#") row[x] = "+";
      else if (row[x] === "+") row[x] = ".";
    }
  }
  for (let i = 1; i <= 14; i++) {
    for (const x of [i - 1, i + 2]) if (x >= 0 && x < SIZE) g[i][x] = ".";
  }
  for (let i = 1; i <= 14; i++) {
    g[i][i] = "#";
    g[i][i + 1] = "#";
  }
  return g.map((r) => r.join(""));
}

const flipH = (rows: PixelRows): string[] =>
  rows.map((r) => r.split("").reverse().join(""));

